// last-generated thumbnail per drawing id. Generating a full canvas export is
// expensive, so we refresh it on a slow throttle (below) and let the normal,
// fast save ride along with whatever's cached rather than rendering every save.
const thumbnailCache = new Map<string, string>();

const queueGenerateThumbnail = throttle(
  async (
    drawingId: string,
    elements: readonly OrderedExcalidrawElement[],
    appState: AppState,
    files: BinaryFiles,
  ) => {
    try {
      const blob = await exportToBlob({
        elements,
        appState: { ...appState, exportBackground: true },
        files,
        mimeType: "image/jpeg",
        quality: 0.7,
        maxWidthOrHeight: 400,
      });
      thumbnailCache.set(drawingId, await getDataURL(blob));
    } catch (error) {
      console.error("failed to generate thumbnail", error);
    }
  },
  15000,
);

const queueSaveDrawing = throttle(
  (
    drawingId: string,
    elements: readonly OrderedExcalidrawElement[],
    appState: AppState,
    files: BinaryFiles,
  ) => {
    saveDrawing(
      drawingId,
      getSyncableElements(elements),
      appState,
      files,
      thumbnailCache.get(drawingId) ?? null,
    ).catch((error) => console.error("failed to save drawing", error));
  },
  SAVE_TO_LOCAL_STORAGE_TIMEOUT,
);

// one-time seed of a curated AI / agentic-architecture / cloud-infra / AI-infra
// shape library, so new users don't land on an empty library panel. Runs once
// per browser (flagged in localStorage) and merges rather than overwrites, so
// it never clobbers anything the user has since added or removed.
const seedDefaultLibraryOnce = (excalidrawAPI: ExcalidrawImperativeAPI) => {
  if (localStorage.getItem(STORAGE_KEYS.DEFAULT_LIBRARY_SEEDED)) {
    return;
  }
  localStorage.setItem(STORAGE_KEYS.DEFAULT_LIBRARY_SEEDED, "true");
  fetch("/library/default-library.excalidrawlib")
    .then((response) => response.blob())
    .then((blob) =>
      excalidrawAPI.updateLibrary({
        libraryItems: blob,
        merge: true,
        defaultStatus: "published",
      }),
    )
    .catch((error) => console.error("failed to seed default library", error));
};

