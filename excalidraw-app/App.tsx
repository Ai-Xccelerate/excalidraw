/** Editable name for the open drawing, shown next to the logo. Writes to
 * appState.name (Excalidraw's scene name), which the debounced save pushes to
 * drawing.title — so the dashboard card and the editor stay in sync. */
const DrawingTitle = ({
  excalidrawAPI,
}: {
  excalidrawAPI: ExcalidrawImperativeAPI | null;
}) => {
  const drawingId = useAtomValue(currentDrawingIdAtom);
  const [name, setName] = useState("");
  const [editing, setEditing] = useState(false);

  useEffect(() => {
    if (excalidrawAPI && drawingId) {
      setName(excalidrawAPI.getAppState().name || "Untitled");
    }
  }, [excalidrawAPI, drawingId]);

  if (!drawingId || !excalidrawAPI) {
    return null;
  }

  const commit = () => {
    setEditing(false);
    const trimmed = name.trim() || "Untitled";
    setName(trimmed);
    excalidrawAPI.updateScene({
      appState: { name: trimmed },
      captureUpdate: CaptureUpdateAction.NEVER,
    });
  };

  return editing ? (
    <input
      className="aix-drawing-title__input"
      autoFocus
      value={name}
      onChange={(event) => setName(event.target.value)}
      onBlur={commit}
      onKeyDown={(event) => {
        if (event.key === "Enter") {
          commit();
        } else if (event.key === "Escape") {
          setName(excalidrawAPI.getAppState().name || "Untitled");
          setEditing(false);
        }
      }}
    />
  ) : (
    <button
      className="aix-drawing-title"
      onClick={() => setEditing(true)}
      title="Rename drawing"
    >
      {name || "Untitled"}
    </button>
  );
};

/** Auth is now first-party (email + password against our own API), so it is
 * always on; this keeps the previously Clerk-gated branches readable. */
const AUTH_ENABLED = true;

const ExcalidrawApp = () => {
  const isCloudExportWindow =
    window.location.pathname === "/excalidraw-plus-export";
  if (isCloudExportWindow) {
    return <ExcalidrawPlusIframeExport />;
  }

  const canvas = (
    <ExcalidrawAPIProvider>
      <ExcalidrawWrapper />
    </ExcalidrawAPIProvider>
  );

  return (
    <AuthProvider>
      <TopErrorBoundary>
        <Provider store={appJotaiStore}>
          <RootView canvas={canvas} />
        </Provider>
      </TopErrorBoundary>
    </AuthProvider>
  );
};

/** Signed-in users land on the dashboard; the canvas stays the entry point for
 * direct drawing links (/d/:id), collab links, and signed-out visitors. */
const RootView = ({ canvas }: { canvas: React.ReactNode }) => {
  const { isLoaded, isSignedIn } = useAuth();
  const [pathname, setPathname] = useState(window.location.pathname);

  useEffect(() => {
    const onPop = () => setPathname(window.location.pathname);
    window.addEventListener("popstate", onPop);
    return () => window.removeEventListener("popstate", onPop);
  }, []);

  const isBareRoot =
    pathname === "/" && !window.location.hash && !window.location.search;

  // /login has to redirect too: signing in flips isSignedIn while the path is
  // still /login, which would otherwise fall through to the canvas and strand
  // the user one step short of the dashboard they just signed in to reach
  useEffect(() => {
    if (isLoaded && isSignedIn && (isBareRoot || pathname === "/login")) {
      window.history.replaceState({}, APP_NAME, "/dashboard");
      setPathname("/dashboard");
    }
  }, [isLoaded, isSignedIn, isBareRoot, pathname]);

  // /reset-password carries a one-time token from the email link and must work
  // for a signed-out visitor, so it is checked before any auth gate
  if (pathname === "/reset-password") {
    const token = new URLSearchParams(window.location.search).get("token");
    return <AuthPage initialMode="reset" resetToken={token} />;
  }
  if (pathname === "/verify-email") {
    const token = new URLSearchParams(window.location.search).get("token");
    return <AuthPage initialMode="verify" verifyToken={token} />;
  }
  if (!isLoaded) {
    return null;
  }
  // the bare root is the front door: a signed-out visitor gets the sign-in
  // screen rather than an anonymous canvas. Deep links are deliberately not
  // gated here — /d/:id, collab #room links and shared scenes carry a hash or
  // search and still open for a signed-out visitor.
  if (
    !isSignedIn &&
    (isBareRoot ||
      pathname === "/dashboard" ||
      pathname === "/settings" ||
      pathname === "/oauth/consent" ||
      pathname === "/login")
  ) {
    return <AuthPage />;
  }
  if (pathname === "/dashboard") {
    return <DashboardPage />;
  }
  if (pathname === "/settings") {
    return <SettingsPage />;
  }
  // an agent sent the user here to approve an MCP connection
  if (pathname === "/oauth/consent") {
    return <OAuthConsentPage />;
  }
  return <>{canvas}</>;
};

